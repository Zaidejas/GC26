"""Generates Scripts/Texts.cs for the Unity version from the texts in the HTML prototype (L = { ru:{...}, en:{...} }).

The HTML prototype is the single source of the game's texts. After editing texts there, run from the repository root:

    python Assets/Microgames/gc26_science_snake/Tools~/gen_texts.py docs/prototype_snake_2.html Assets/Microgames/gc26_science_snake/Scripts/Texts.cs

(The Tools~ folder ends with "~", so Unity ignores it.)
"""
import sys, re, json
html, out = sys.argv[1], sys.argv[2]
s = open(html, encoding='utf-8').read()
STR = r'"(?:[^"\\]|\\.)*"'
start = s.index("const L = {")
ru_a = s.index(" ru:{", start); en_a = s.index(" en:{", ru_a); end = s.index("\n};", en_a)
blocks = {"Ru": s[ru_a:en_a], "En": s[en_a:end]}

def take(block, name, opener, closer):
    m = re.search(r'\n  ' + name + r':' + re.escape(opener), block)
    a = m.end(); depth = 1; i = a
    while depth:
        ch = block[i]
        if ch == '"':
            i += 1
            while block[i] != '"':
                i += 2 if block[i] == '\\' else 1
        elif ch == opener: depth += 1
        elif ch == closer: depth -= 1
        i += 1
    inner = block[a:i-1]
    return inner, block[:m.start()] + block[i:]

def cs(x):  # C# string literal
    return json.dumps(json.loads(x) if x.startswith('"') else x, ensure_ascii=False)

lines = ["// <auto-generated> from docs/prototype_snake_2.html by gen_texts.py. Edit the texts there, then regenerate.",
         "using System.Collections.Generic;", "", "namespace GC26.ScienceSnake", "{",
         "    public sealed class Lang", "    {",
         "        public Dictionary<string, string> S;",
         "        public Dictionary<string, string> Phase, Touch;",
         "        public string[] Hunger, Simple, Greed;",
         "        public (string title, string text)[] Tut;", "    }", "",
         "    public static class Texts", "    {"]
for name, b in blocks.items():
    ph, b = take(b, "ph", "{", "}")
    touch, b = take(b, "touch", "{", "}")
    tut, b = take(b, "tutSteps", "[", "]")
    _, b = take(b, "intro", "[", "]")
    greed, b = take(b, "greedLines", "[", "]")
    hunger, b = take(b, "hungerTexts", "[", "]")
    simple, b = take(b, "simpleFacts", "[", "]")
    pairs = re.findall(r'(?<![\w"])(\w+):(' + STR + ')', b)
    kv = lambda src: re.findall(r'(\w+):(' + STR + ')', src)
    lines.append(f"        public static readonly Lang {name} = new Lang")
    lines.append("        {")
    lines.append("            S = new Dictionary<string, string>")
    lines.append("            {")
    for k, v in pairs:
        lines.append(f"                [{json.dumps(k)}] = {cs(v)},")
    lines.append("            },")
    lines.append("            Phase = new Dictionary<string, string> { " + ", ".join(f"[{json.dumps(k)}] = {cs(v)}" for k, v in kv(ph)) + " },")
    lines.append("            Touch = new Dictionary<string, string> { " + ", ".join(f"[{json.dumps(k)}] = {cs(v)}" for k, v in kv(touch)) + " },")
    lines.append("            Hunger = new[] {\n" + ",\n".join("                " + cs(x) for x in re.findall(STR, hunger)) + "\n            },")
    lines.append("            Simple = new[] {\n" + ",\n".join("                " + cs(x) for x in re.findall(r'\["[hc]",(' + STR + r')\]', simple)) + "\n            },")
    lines.append("            Greed = new[] {\n" + ",\n".join("                " + cs(x) for x in re.findall(STR, greed)) + "\n            },")
    tuts = re.findall(r'\{title:(' + STR + r'), text:(' + STR + r')\}', tut)
    lines.append("            Tut = new[] {\n" + ",\n".join(f"                ({cs(t)}, {cs(x)})" for t, x in tuts) + "\n            },")
    lines.append("        };")
    lines.append("")
lines += ["    }", "}", ""]
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("ok", out)
