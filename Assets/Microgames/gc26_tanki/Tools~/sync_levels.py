"""Keeps the maps in one place: Scripts/Rules/Levels.cs is the source for the campaign and the arena,
Tools~/assault_maps.txt for the assault maps. This script checks the assault maps, writes them into
Levels.cs, and copies every map into the browser version (Web~/steel-line.html).

usage: python sync_levels.py        (run from anywhere; paths are relative to this file)
"""
import os
import re
import sys
from collections import deque

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, "..")
LEVELS_CS = os.path.join(GAME, "Scripts", "Rules", "Levels.cs")
HTML = os.path.join(GAME, "Web~", "steel-line.html")
ASSAULT_TXT = os.path.join(HERE, "assault_maps.txt")
W, H = 11, 17

CS_START = "        // ---- Assault maps: generated by Tools~/sync_levels.py from Tools~/assault_maps.txt ----"
CS_END = "        // ---- End of assault maps ----"
JS_START = "// Generated from Scripts/Rules/Levels.cs by Tools~/sync_levels.py."
JS_END = "// End of generated maps."


def read(path):
    with open(path, encoding="utf-8-sig") as f:
        return f.read()


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def parse_cs_levels(cs):
    """Every new LevelDef("name", "waves", rows...) in order, campaign first, then the arena."""
    found = []
    for m in re.finditer(r'new LevelDef\("([^"]*)",\s*"([^"]*)",((?:\s*"[^"]*",?)+)\)', cs):
        rows = re.findall(r'"([^"]*)"', m.group(3))
        found.append((m.group(1), m.group(2), rows))
    return found


def parse_assault(text):
    lines = [l.rstrip() for l in text.splitlines() if l.strip() and not l.startswith(";")]
    maps, i = [], 0
    while i < len(lines):
        name, waves = [x.strip() for x in lines[i].split("|")]
        maps.append((name, waves, lines[i + 1:i + 1 + H]))
        i += 1 + H
    return maps


def check_assault(name, rows):
    problems = []
    if len(rows) != H or any(len(r) != W for r in rows):
        return ["%s: needs %d rows of %d cells" % (name, H, W)]
    count = lambda c: sum(r.count(c) for r in rows)
    if count("C") != 1: problems.append(name + ": needs exactly one enemy reactor C")
    if count("P") != 1: problems.append(name + ": needs exactly one player start P")
    if count("B"): problems.append(name + ": an assault map has no own base B")
    if count("E") < 2: problems.append(name + ": needs at least two enemy gates E")
    grid = {(x, y): rows[y][x] for y in range(H) for x in range(W)}

    def reach(start):
        seen, queue = {start}, deque([start])
        while queue:
            x, y = queue.popleft()
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                n = (x + dx, y + dy)
                if n in grid and n not in seen and grid[n] not in "@~CT":
                    seen.add(n)
                    queue.append(n)
        return seen

    if not problems:
        p = next(k for k, v in grid.items() if v == "P")
        c = next(k for k, v in grid.items() if v == "C")
        r = reach(p)
        if not any((c[0] + dx, c[1] + dy) in r for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
            problems.append(name + ": the reactor cannot be reached from P")
        if not all(k in r for k, v in grid.items() if v == "E"):
            problems.append(name + ": a gate cannot reach the player")
    return problems


def cs_block(maps):
    out = [CS_START,
           "        /// <summary>Assault: the player attacks the enemy reactor (C) past turrets (T). Waves loop until it falls.</summary>",
           "        public static readonly LevelDef[] Assault =", "        {"]
    for i, (name, waves, rows) in enumerate(maps):
        out.append('            new LevelDef("%s", "%s",' % (name, waves))
        for j, row in enumerate(rows):
            out.append('                "%s"%s' % (row, ")" if j == len(rows) - 1 else ","))
        out[-1] += "," if i < len(maps) - 1 else ""
        if i < len(maps) - 1:
            out.append("")
    out += ["        };", CS_END]
    return "\n".join(out)


def js_map(name, waves, rows):
    return '{ name: "%s", waves: "%s", rows: [%s] }' % (name, waves, ", ".join('"%s"' % r for r in rows))


def main():
    cs = read(LEVELS_CS).replace("\r\n", "\n")
    assault = parse_assault(read(ASSAULT_TXT))
    problems = [p for name, _, rows in assault for p in check_assault(name, rows)]
    if problems:
        print("\n".join(problems))
        sys.exit(1)

    block = cs_block(assault)
    if CS_START in cs:
        cs = re.sub(re.escape(CS_START) + r".*?" + re.escape(CS_END), lambda _: block, cs, flags=re.S)
    else:
        # Before the closing braces of the class and the namespace.
        cut = cs.rstrip().rfind("}", 0, cs.rstrip().rfind("}"))
        cs = cs[:cut].rstrip() + "\n\n" + block + "\n    }\n}\n"
    write(LEVELS_CS, cs)

    levels = parse_cs_levels(cs)
    names = {a[0] for a in assault}
    campaign = [l for l in levels if l[0] != "Арена" and l[0] not in names]
    arena = next(l for l in levels if l[0] == "Арена")
    js = "\n".join([
        JS_START,
        "const LEVELS = [",
        ",\n".join("  " + js_map(*l) for l in campaign),
        "];",
        "const SURVIVAL = " + js_map(*arena) + ";",
        "const ASSAULT = [",
        ",\n".join("  " + js_map(*a) for a in assault),
        "];",
        JS_END,
    ])
    html = read(HTML)
    if JS_START in html:
        html = re.sub(re.escape(JS_START) + r".*?" + re.escape(JS_END), lambda _: js, html, flags=re.S)
    else:
        html = re.sub(r"// Generated from Assets/Scripts/Core/Levels\.cs\.\nconst LEVELS = \[.*?\nconst SURVIVAL = [^\n]*\n",
                      lambda _: js + "\n", html, flags=re.S)
    write(HTML, html)
    print("synced %d campaign maps, the arena and %d assault maps" % (len(campaign), len(assault)))


if __name__ == "__main__":
    main()
